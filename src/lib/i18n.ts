export function statusLabel(status: VerificationStatus, lang: Language): string {
  if (lang === 'en') return status;
  switch (status) {
    case 'Verified':
      return 'Verified';
    case 'Mismatch':
      return 'Mismatch';
    case 'Insufficient Evidence':
      return 'Insufficient Evidence';
    case 'Needs Human Review':
      return 'Needs Human Review';
  }
}
